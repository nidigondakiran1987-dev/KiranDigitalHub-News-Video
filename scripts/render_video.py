"""Generate bilingual Shorts and one landscape compilation using Edge TTS and FFmpeg."""
import asyncio
import json
import os
import re
import shutil
import subprocess
import textwrap
from pathlib import Path
from urllib.parse import urlparse

import edge_tts
from PIL import Image, ImageDraw, ImageFont

ROOT = Path('output')
WORK = ROOT / 'work'
TE_FONT = '/usr/share/fonts/truetype/noto/NotoSansTelugu-Regular.ttf'
EN_FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
TE_VOICE = os.getenv('TE_VOICE', 'te-IN-ShrutiNeural')
EN_VOICE = os.getenv('EN_VOICE', 'en-IN-NeerjaNeural')


def run(args):
    subprocess.run(args, check=True, stdout=subprocess.DEVNULL)


def font(path, size):
    if not Path(path).exists():
        raise FileNotFoundError(f'Missing font: {path}. Install fonts-noto-core.')
    return ImageFont.truetype(path, size)


def wrapped(draw, text, fnt, max_width, max_lines=11):
    # Wrap by actual rendered width; preserves Telugu words instead of splitting glyph clusters.
    words = re.split(r'\s+', text.strip())
    lines, current = [], ''
    for word in words:
        candidate = (current + ' ' + word).strip()
        if draw.textbbox((0, 0), candidate, font=fnt)[2] <= max_width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    if len(lines) > max_lines:
        lines = lines[:max_lines]
        last = lines[-1]
        while last and draw.textbbox((0, 0), last + '…', font=fnt)[2] > max_width:
            last = last[:-1]
        lines[-1] = last + '…'
    return lines


def slide(path, size, title, body, lang, source, date):
    w, h = size
    im = Image.new('RGB', size, '#0b172a')
    d = ImageDraw.Draw(im)
    scale = w / 1080
    margin = int(70 * scale)
    d.rectangle((0, 0, w, int(20 * scale)), fill='#35c6dc')
    d.text((margin, int(70 * scale)), 'KIRANDIGITALHUB', font=font(EN_FONT, int(47 * scale)), fill='#6be1ee')
    d.text((margin, int(145 * scale)), 'VERIFIED NEWS  •  ' + date, font=font(EN_FONT, int(26 * scale)), fill='#b5c7df')
    # Distinct headline area; slides also serve as visible subtitles for narration.
    head_font = font(EN_FONT, int((48 if h > w else 39) * scale))
    top = int((315 if h > w else 245) * scale)
    for line in wrapped(d, title, head_font, w - 2 * margin, 4):
        d.text((margin, top), line, font=head_font, fill='#ffffff')
        top += int(73 * scale)
    d.line((margin, top + 12, w - margin, top + 12), fill='#35c6dc', width=max(2, int(3 * scale)))
    top += int(68 * scale)
    is_te = lang == 'te'
    body_font = font(TE_FONT if is_te else EN_FONT, int((43 if h > w else 33) * scale))
    max_lines = 15 if h > w else 5
    line_h = int((76 if h > w else 57) * scale)
    footer_top = h - int((190 if h > w else 135) * scale)
    for line in wrapped(d, body, body_font, w - 2 * margin, max_lines):
        if top + line_h >= footer_top:
            break
        d.text((margin, top), line, font=body_font, fill='#e4edf8', stroke_width=0)
        top += line_h
    d.rectangle((0, footer_top, w, h), fill='#122742')
    d.text((margin, footer_top + int(27 * scale)), 'SOURCE: ' + source[:65], font=font(EN_FONT, int(24 * scale)), fill='#b5c7df')
    d.text((margin, footer_top + int(79 * scale)), 'kirandigitalhub.com  •  Review before publishing', font=font(EN_FONT, int(23 * scale)), fill='#6be1ee')
    im.save(path)


async def tts(text, voice, target):
    # Edge TTS uses a network service; retries help transient connection failures.
    last = None
    for attempt in range(3):
        try:
            await edge_tts.Communicate(text=text, voice=voice, rate='-5%').save(str(target))
            if target.stat().st_size < 1000:
                raise RuntimeError('Audio unexpectedly small')
            return
        except Exception as exc:
            last = exc
            await asyncio.sleep(2 * (attempt + 1))
    raise RuntimeError(f'Edge TTS failed after retries: {last}')


def segment(image_path, audio_path, video_path, w, h):
    run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-loop', '1', '-framerate', '1', '-i', str(image_path),
         '-i', str(audio_path), '-vf', f'fps=24,scale={w}:{h},format=yuv420p',
         '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '25', '-c:a', 'aac', '-b:a', '128k',
         '-ar', '44100', '-ac', '2', '-shortest', '-movflags', '+faststart', str(video_path)])


def concat(parts, destination):
    # Paths are generated by this script and contain no single quotes.
    listfile = WORK / ('concat_' + destination.stem + '.txt')
    listfile.write_text(''.join(f"file '{p.resolve()}'\n" for p in parts), encoding='utf-8')
    run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'concat', '-safe', '0',
         '-i', str(listfile), '-c', 'copy', '-movflags', '+faststart', str(destination)])


async def main():
    data = json.loads((ROOT / 'news.json').read_text(encoding='utf-8'))
    items = data if isinstance(data, list) else data.get('items', [])
    if not items:
        print('No approved news; skipping video generation')
        return
    WORK.mkdir(parents=True, exist_ok=True)
    long_parts = []
    # Keep GitHub runner processing bounded; change MAX_NEWS deliberately if required.
    limit = int(os.getenv('MAX_NEWS', '5'))
    for i, item in enumerate(items[:limit], 1):
        title = item['title_en']
        telugu = item['script_te']
        # English narration is the approved English headline, not an invented article summary.
        en_text = title
        domain = urlparse(item['source_url']).hostname or 'Official source'
        aud_te, aud_en = WORK / f'{i:02}_te.mp3', WORK / f'{i:02}_en.mp3'
        print(f'Generating narration {i}/{min(len(items), limit)}: {title[:70]}', flush=True)
        await tts(telugu[:1800], TE_VOICE, aud_te)
        await tts(en_text[:1000], EN_VOICE, aud_en)
        short_parts = []
        for fmt, size in [('short', (1080, 1920)), ('long', (1920, 1080))]:
            current = []
            for lang, body, audio in [('te', telugu, aud_te), ('en', en_text, aud_en)]:
                png = WORK / f'{i:02}_{fmt}_{lang}.png'
                mp4 = WORK / f'{i:02}_{fmt}_{lang}.mp4'
                slide(png, size, title, body, lang, domain, data['date_ist'])
                segment(png, audio, mp4, *size)
                current.append(mp4)
            if fmt == 'short':
                concat(current, ROOT / f'KDH_Short_{i:02}.mp4')
            else:
                long_parts.extend(current)
    if long_parts:
        concat(long_parts, ROOT / 'KDH_Daily_Long.mp4')
    print('Video generation finished. Files in output/*.mp4')

if __name__ == '__main__':
    asyncio.run(main())
